"""Dockerfile generator for Kapitan.

This module provides a kadet-based generator that creates Dockerfiles
from inventory parameters.

Usage:
    1. Add dockerfiles parameter to your target inventory
    2. Include kapitan.generators.docker class
    3. Dockerfiles will be generated during compilation

Example inventory:
    parameters:
      generators:
        docker:
          dockerfiles:
            my-app:
              base_image: python:3.11-slim
              workdir: /app
              packages:
                - curl
                - git
              copy:
                - src: requirements.txt
                  dst: .
              run:
                - pip install -r requirements.txt
              cmd: ["python", "main.py"]
"""

__version__ = "1.4.3"

import json
from typing import Any

from kapitan.inputs.kadet import BaseObj, inventory


inventory_data = inventory()


_OMEGACONF_TYPES: tuple[type, ...]
try:
    from omegaconf import DictConfig, ListConfig

    _OMEGACONF_TYPES = (DictConfig, ListConfig)
except ImportError:
    _OMEGACONF_TYPES = ()


# Valid values for validation (derived from schema)
VALID_PACKAGE_MANAGERS = {"auto", "apt", "apk", "dnf", "pip"}
VALID_NETWORK_MODES = {"default", "none", "host"}
VALID_SECURITY_MODES = {"sandbox", "insecure"}

# Package manager detection patterns
ALPINE_PATTERNS = ["alpine"]
DEBIAN_PATTERNS = ["debian", "ubuntu"]
REDHAT_PATTERNS = ["fedora", "centos", "rhel", "rocky", "alma"]

# Dockerfile header lines
DOCKERFILE_HEADER = [
    "# Generated by Kapitan Docker Generator",
    "# Do not edit manually - changes will be overwritten",
    "",
]


def _validate_enum(value: Any, valid_values: set, field_name: str) -> None:
    """Validate that a value is in a set of valid values.

    Args:
        value: Value to validate
        valid_values: Set of allowed values
        field_name: Name of the field for error messages

    Raises:
        ValueError: If value is not in valid_values
    """
    if value is not None and value not in valid_values:
        raise ValueError(
            f"Invalid {field_name} '{value}'. "
            f"Must be one of: {', '.join(sorted(valid_values))}"
        )


def validate_dockerfile_config(name: str, config: dict) -> None:
    """Validate Dockerfile configuration against schema constraints.

    Args:
        name: Name of the Dockerfile for error messages
        config: Dockerfile configuration dictionary

    Raises:
        ValueError: If configuration is invalid
    """
    # Validate base_image is present for non-multi-stage builds
    if "stages" not in config and not config.get("base_image"):
        raise ValueError(f"Dockerfile '{name}': base_image is required")

    # Validate package_manager enum
    pkg_manager = config.get("package_manager", "auto")
    _validate_enum(pkg_manager, VALID_PACKAGE_MANAGERS, f"package_manager in '{name}'")

    # Validate uid/gid ranges
    uid = config.get("uid")
    if uid is not None and (uid < 0 or uid > 65534):
        raise ValueError(
            f"Dockerfile '{name}': uid must be between 0 and 65534, got {uid}"
        )

    gid = config.get("gid")
    if gid is not None and (gid < 0 or gid > 65534):
        raise ValueError(
            f"Dockerfile '{name}': gid must be between 0 and 65534, got {gid}"
        )

    # Validate expose ports
    for port in config.get("expose", []):
        if isinstance(port, int) and (port < 1 or port > 65535):
            raise ValueError(
                f"Dockerfile '{name}': port must be between 1 and 65535, got {port}"
            )

    # Validate run commands with options
    for cmd in config.get("run", []):
        if isinstance(cmd, dict):
            network = cmd.get("network")
            _validate_enum(network, VALID_NETWORK_MODES, f"run.network in '{name}'")
            security = cmd.get("security")
            _validate_enum(security, VALID_SECURITY_MODES, f"run.security in '{name}'")

    # Validate stages recursively; nested stages would validate and then be
    # silently dropped by the builders, so reject them outright.
    for i, stage in enumerate(config.get("stages", [])):
        stage_name = stage.get("stage_name", f"stage-{i}")
        if "stages" in stage:
            raise ValueError(
                f"Dockerfile '{name}/{stage_name}': nested stages are not supported"
            )
        validate_dockerfile_config(f"{name}/{stage_name}", stage)


def _convert_to_dict(obj: Any) -> Any:
    """Recursively convert OmegaConf / BaseObj objects to plain Python dicts."""
    if _OMEGACONF_TYPES and isinstance(obj, _OMEGACONF_TYPES):
        from omegaconf import OmegaConf

        return _convert_to_dict(OmegaConf.to_container(obj, resolve=True))
    if hasattr(obj, "to_dict"):
        return obj.to_dict()
    if hasattr(obj, "root"):
        return _convert_to_dict(obj.root)
    if isinstance(obj, dict):
        return {k: _convert_to_dict(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_convert_to_dict(item) for item in obj]
    return obj


def detect_package_manager(base_image: str) -> str:
    """Detect the appropriate package manager based on the base image name.

    Args:
        base_image: Docker base image name (e.g., 'python:3.11-slim')

    Returns:
        Package manager command: 'apk', 'apt', or 'dnf'
    """
    base_image_lower = base_image.lower()

    if any(pattern in base_image_lower for pattern in ALPINE_PATTERNS):
        return "apk"
    if any(pattern in base_image_lower for pattern in DEBIAN_PATTERNS):
        return "apt"
    if any(pattern in base_image_lower for pattern in REDHAT_PATTERNS):
        return "dnf"
    return "apt"  # Default to apt for unknown images


def format_json_array(items: list) -> str:
    """Format a Python list as a JSON array string for Dockerfile instructions.

    Args:
        items: List of strings to format

    Returns:
        JSON-formatted array string (e.g., '["python", "main.py"]')
    """
    return json.dumps([str(item) for item in items])


def _directive_value(value: Any, field: str) -> str:
    """Render a scalar for a single-line Dockerfile directive.

    Rejects newlines: a value like "alpine\nCOPY /etc/secrets /out" would
    otherwise inject arbitrary Dockerfile instructions.
    """
    text = str(value)
    if "\n" in text or "\r" in text:
        raise ValueError(f"Dockerfile {field} must not contain newlines: {text!r}")
    return text


def _quoted_value(value: Any, field: str) -> str:
    """Render a quoted, escaped value for ENV/LABEL directives."""
    text = _directive_value(value, field)
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


class DockerfileBuilder:
    """Builder class for constructing Dockerfiles from configuration dictionaries.

    This class takes a configuration dictionary and generates a valid Dockerfile
    by processing each instruction type in the correct order.
    """

    def __init__(self, dockerfile_config: dict):
        """Initialize the builder with configuration.

        Args:
            dockerfile_config: Dictionary containing Dockerfile configuration from inventory
        """
        self.dockerfile_config = _convert_to_dict(dockerfile_config)
        self.dockerfile_lines: list[str] = []

    def build(self) -> str:
        """Build the complete Dockerfile content.

        Returns:
            String containing the complete Dockerfile
        """
        self._add_header_comment()
        self._add_from_instruction()
        self._add_label_instructions()
        self._add_arg_instructions()
        self._add_env_instructions()
        self._add_workdir_instruction()
        self._add_package_installation()
        self._add_user_setup_instructions()
        self._add_copy_instructions()
        self._add_run_instructions()
        self._add_volume_instructions()
        self._add_expose_instructions()
        self._add_healthcheck_instruction()
        self._add_entrypoint_instruction()
        self._add_cmd_instruction()

        return "\n".join(self.dockerfile_lines) + "\n"

    def _add_header_comment(self) -> None:
        """Add header comment with generation notice."""
        self.dockerfile_lines.extend(DOCKERFILE_HEADER)

    def _add_from_instruction(self) -> None:
        """Add FROM instruction with optional platform and stage name."""
        base_image = self.dockerfile_config["base_image"]
        target_platform = self.dockerfile_config.get("platform")
        stage_name = self.dockerfile_config.get("stage_name")

        from_instruction = "FROM"
        if target_platform:
            from_instruction += (
                f" --platform={_directive_value(target_platform, 'platform')}"
            )
        from_instruction += f" {_directive_value(base_image, 'base_image')}"
        if stage_name:
            from_instruction += f" AS {_directive_value(stage_name, 'stage_name')}"

        self.dockerfile_lines.append(from_instruction)
        self.dockerfile_lines.append("")

    def _add_label_instructions(self) -> None:
        """Add LABEL instructions for image metadata."""
        image_labels = self.dockerfile_config.get("labels", {})
        if image_labels:
            for label_key, label_value in image_labels.items():
                self.dockerfile_lines.append(
                    f"LABEL {_directive_value(label_key, 'label key')}="
                    f"{_quoted_value(label_value, 'label value')}"
                )
            self.dockerfile_lines.append("")

    def _add_arg_instructions(self) -> None:
        """Add ARG instructions for build-time variables."""
        build_args = self.dockerfile_config.get("args", {})
        if build_args:
            for arg_name, arg_default_value in build_args.items():
                arg_name = _directive_value(arg_name, "arg name")
                if arg_default_value is not None:
                    arg_value = _directive_value(arg_default_value, "arg value")
                    self.dockerfile_lines.append(f"ARG {arg_name}={arg_value}")
                else:
                    self.dockerfile_lines.append(f"ARG {arg_name}")
            self.dockerfile_lines.append("")

    def _add_env_instructions(self) -> None:
        """Add ENV instructions for runtime environment variables."""
        environment_variables = self.dockerfile_config.get("env", {})
        if environment_variables:
            for env_name, env_value in environment_variables.items():
                self.dockerfile_lines.append(
                    f"ENV {_directive_value(env_name, 'env name')}="
                    f"{_quoted_value(env_value, 'env value')}"
                )
            self.dockerfile_lines.append("")

    def _add_workdir_instruction(self) -> None:
        """Add WORKDIR instruction for setting the working directory."""
        working_directory = self.dockerfile_config.get("workdir")
        if working_directory:
            self.dockerfile_lines.append(
                f"WORKDIR {_directive_value(working_directory, 'workdir')}"
            )
            self.dockerfile_lines.append("")

    def _add_user_setup_instructions(self) -> None:
        """Add USER instruction and optional user/group creation commands."""
        container_user = self.dockerfile_config.get("user")
        should_create_user = self.dockerfile_config.get("create_user", False)

        if should_create_user and container_user:
            user = _directive_value(container_user, "user")
            user_id = self.dockerfile_config.get("uid", 1000)
            group_id = self.dockerfile_config.get("gid", 1000)
            base_image = self.dockerfile_config.get("base_image", "")
            package_manager = detect_package_manager(base_image)
            if package_manager == "apk":
                # busybox userland
                self.dockerfile_lines.append(f"RUN addgroup -g {group_id} {user} && \\")
                self.dockerfile_lines.append(
                    f"    adduser -D -u {user_id} -G {user} {user}"
                )
            else:
                # shadow-utils (Debian/Ubuntu/RHEL family)
                self.dockerfile_lines.append(f"RUN groupadd -g {group_id} {user} && \\")
                self.dockerfile_lines.append(
                    f"    useradd -m -u {user_id} -g {user} {user}"
                )
            self.dockerfile_lines.append("")

        if container_user:
            self.dockerfile_lines.append(
                f"USER {_directive_value(container_user, 'user')}"
            )
            self.dockerfile_lines.append("")

    def _add_package_installation(self) -> None:
        """Add RUN instructions for installing system packages."""
        packages_to_install = self.dockerfile_config.get("packages", [])
        package_manager_override = self.dockerfile_config.get("package_manager", "auto")

        if not packages_to_install:
            return

        base_image = self.dockerfile_config.get("base_image", "")

        if package_manager_override == "auto":
            package_manager = detect_package_manager(base_image)
        else:
            package_manager = package_manager_override

        package_list_string = " ".join(
            _directive_value(package, "package") for package in packages_to_install
        )

        if package_manager == "apk":
            self.dockerfile_lines.append(
                f"RUN apk add --no-cache {package_list_string}"
            )
        elif package_manager == "apt":
            self.dockerfile_lines.append("RUN apt-get update && \\")
            self.dockerfile_lines.append(
                f"    apt-get install -y --no-install-recommends {package_list_string} && \\"
            )
            self.dockerfile_lines.append("    rm -rf /var/lib/apt/lists/*")
        elif package_manager == "dnf":
            self.dockerfile_lines.append(
                f"RUN dnf install -y {package_list_string} && dnf clean all"
            )
        elif package_manager == "pip":
            self.dockerfile_lines.append(
                f"RUN pip install --no-cache-dir {package_list_string}"
            )

        self.dockerfile_lines.append("")

    def _add_copy_instructions(self) -> None:
        """Add COPY instructions for copying files into the image."""
        copy_directives = self.dockerfile_config.get("copy", [])
        if not copy_directives:
            return

        for copy_item in copy_directives:
            if isinstance(copy_item, dict):
                for key, value in copy_item.items():
                    _directive_value(value, f"copy {key}")
                source_path = copy_item.get("src", ".")
                destination_path = copy_item.get("dst", ".")
                source_stage = copy_item.get("from")
                ownership = copy_item.get("chown")
                permissions = copy_item.get("chmod")

                copy_instruction = "COPY"
                if source_stage:
                    copy_instruction += f" --from={source_stage}"
                if ownership:
                    copy_instruction += f" --chown={ownership}"
                if permissions:
                    copy_instruction += f" --chmod={permissions}"
                copy_instruction += f" {source_path} {destination_path}"
                self.dockerfile_lines.append(copy_instruction)
            else:
                # Simple string format: "src dst" or just "src"
                self.dockerfile_lines.append(
                    f"COPY {_directive_value(copy_item, 'copy')}"
                )

        self.dockerfile_lines.append("")

    def _add_run_instructions(self) -> None:
        """Add RUN instructions for executing commands during build."""
        run_commands = self.dockerfile_config.get("run", [])
        if not run_commands:
            return

        for command in run_commands:
            if isinstance(command, dict):
                # Complex run with mount or other options
                for key, value in command.items():
                    _directive_value(value, f"run {key}")
                shell_command = command.get("command", "")
                mount_option = command.get("mount")
                network_option = command.get("network")
                security_option = command.get("security")

                run_instruction = "RUN"
                if mount_option:
                    run_instruction += f" --mount={mount_option}"
                if network_option:
                    run_instruction += f" --network={network_option}"
                if security_option:
                    run_instruction += f" --security={security_option}"
                run_instruction += f" {shell_command}"
                self.dockerfile_lines.append(run_instruction)
            elif isinstance(command, list):
                # Multi-line command joined with &&
                chained_commands = " && \\\n    ".join(
                    _directive_value(part, "run") for part in command
                )
                self.dockerfile_lines.append(f"RUN {chained_commands}")
            else:
                self.dockerfile_lines.append(f"RUN {_directive_value(command, 'run')}")

        self.dockerfile_lines.append("")

    def _add_volume_instructions(self) -> None:
        """Add VOLUME instructions for declaring mount points."""
        volume_paths = self.dockerfile_config.get("volumes", [])
        if volume_paths:
            for volume_path in volume_paths:
                self.dockerfile_lines.append(
                    f"VOLUME {_directive_value(volume_path, 'volume')}"
                )
            self.dockerfile_lines.append("")

    def _add_expose_instructions(self) -> None:
        """Add EXPOSE instructions for documenting container ports."""
        exposed_ports = self.dockerfile_config.get("expose", [])
        if exposed_ports:
            for port_number in exposed_ports:
                self.dockerfile_lines.append(
                    f"EXPOSE {_directive_value(port_number, 'expose')}"
                )
            self.dockerfile_lines.append("")

    def _add_healthcheck_instruction(self) -> None:
        """Add HEALTHCHECK instruction for container health monitoring."""
        healthcheck_config = self.dockerfile_config.get("healthcheck")
        if not healthcheck_config:
            return

        if isinstance(healthcheck_config, str):
            if healthcheck_config != "NONE":
                raise ValueError(
                    "healthcheck: the only string value is 'NONE'; use a dict "
                    f"with 'cmd' for check commands, got {healthcheck_config!r}"
                )
            self.dockerfile_lines.append("HEALTHCHECK NONE")
        else:
            healthcheck_instruction = "HEALTHCHECK"

            for key, value in healthcheck_config.items():
                for part in value if isinstance(value, list) else [value]:
                    _directive_value(part, f"healthcheck {key}")
            check_interval = healthcheck_config.get("interval")
            check_timeout = healthcheck_config.get("timeout")
            startup_period = healthcheck_config.get("start_period")
            retry_count = healthcheck_config.get("retries")

            if check_interval:
                healthcheck_instruction += f" --interval={check_interval}"
            if check_timeout:
                healthcheck_instruction += f" --timeout={check_timeout}"
            if startup_period:
                healthcheck_instruction += f" --start-period={startup_period}"
            if retry_count:
                healthcheck_instruction += f" --retries={retry_count}"

            health_command = healthcheck_config.get(
                "cmd", healthcheck_config.get("command")
            )
            if not health_command:
                # A HEALTHCHECK line without CMD is invalid Dockerfile syntax
                raise ValueError("healthcheck requires 'cmd' (or 'command')")
            if isinstance(health_command, list):
                healthcheck_instruction += f" CMD {format_json_array(health_command)}"
            else:
                healthcheck_instruction += f" CMD {health_command}"

            self.dockerfile_lines.append(healthcheck_instruction)

        self.dockerfile_lines.append("")

    def _add_entrypoint_instruction(self) -> None:
        """Add ENTRYPOINT instruction for container startup command."""
        container_entrypoint = self.dockerfile_config.get("entrypoint")
        if container_entrypoint:
            if isinstance(container_entrypoint, list):
                entrypoint_json = format_json_array(container_entrypoint)
                self.dockerfile_lines.append(f"ENTRYPOINT {entrypoint_json}")
            else:
                self.dockerfile_lines.append(
                    f"ENTRYPOINT {_directive_value(container_entrypoint, 'entrypoint')}"
                )
            self.dockerfile_lines.append("")

    def _add_cmd_instruction(self) -> None:
        """Add CMD instruction for default container command."""
        default_command = self.dockerfile_config.get("cmd")
        if default_command:
            if isinstance(default_command, list):
                command_json = format_json_array(default_command)
                self.dockerfile_lines.append(f"CMD {command_json}")
            else:
                self.dockerfile_lines.append(
                    f"CMD {_directive_value(default_command, 'cmd')}"
                )

        self.dockerfile_lines.append("")


class MultiStageDockerfileBuilder:
    """Builder for multi-stage Dockerfiles with multiple build stages.

    This class handles Dockerfiles that contain multiple FROM instructions,
    each representing a different build stage.
    """

    def __init__(self, multistage_config: dict):
        """Initialize multi-stage builder.

        Args:
            multistage_config: Dictionary containing multi-stage Dockerfile configuration
        """
        self.multistage_config = _convert_to_dict(multistage_config)

    def build(self) -> str:
        """Build multi-stage Dockerfile content.

        Returns:
            String containing the complete multi-stage Dockerfile
        """
        dockerfile_lines = list(DOCKERFILE_HEADER)

        build_stages = self.multistage_config.get("stages", [])
        for stage_index, stage_config in enumerate(build_stages):
            if stage_index > 0:
                dockerfile_lines.append("")
                dockerfile_lines.append("# ---")
                dockerfile_lines.append("")

            stage_builder = DockerfileBuilder(stage_config)
            # Skip header for subsequent stages
            stage_builder._add_header_comment = lambda: None  # type: ignore[method-assign]
            stage_content = stage_builder.build()
            dockerfile_lines.append(stage_content.strip())

        return "\n".join(dockerfile_lines) + "\n"


def generate_dockerfile_content(dockerfile_name: str, dockerfile_config: dict) -> str:
    """Generate a Dockerfile from configuration dictionary.

    Args:
        dockerfile_name: Name identifier for the Dockerfile
        dockerfile_config: Configuration dictionary from inventory

    Returns:
        String containing the Dockerfile content

    Raises:
        ValueError: If configuration is invalid
    """
    normalized_config = _convert_to_dict(dockerfile_config)

    # Validate configuration before building
    validate_dockerfile_config(dockerfile_name, normalized_config)

    builder: DockerfileBuilder | MultiStageDockerfileBuilder
    if "stages" in normalized_config:
        builder = MultiStageDockerfileBuilder(normalized_config)
    else:
        builder = DockerfileBuilder(normalized_config)

    return builder.build()


def main(input_params: dict) -> BaseObj:
    """Main entry point for the Kapitan generator.

    Args:
        input_params: Input parameters from Kapitan

    Returns:
        BaseObj containing generated Dockerfiles
    """
    output_object = BaseObj()

    docker_config = _convert_to_dict(
        inventory_data.parameters.get("generators", {}).get("docker", {})
    )
    dockerfile_definitions = docker_config.get("dockerfiles", {})
    base_output_path = input_params.get("output_path", "")

    for dockerfile_name, dockerfile_config in dockerfile_definitions.items():
        dockerfile_content = generate_dockerfile_content(
            dockerfile_name, dockerfile_config
        )

        # Determine output path
        component_name = dockerfile_config.get("component", dockerfile_name)
        if base_output_path:
            output_file_path = f"{base_output_path}/{component_name}/Dockerfile"
        else:
            output_file_path = f"{component_name}/Dockerfile"

        output_object.root[output_file_path] = dockerfile_content

    return output_object


